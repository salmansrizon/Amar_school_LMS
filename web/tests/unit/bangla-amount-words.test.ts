import { describe, it, expect } from 'vitest'
import { banglaAmountInWords as w } from '@/lib/bangla-amount-words'

describe('banglaAmountInWords', () => {
  it.each([
    [0, 'শূন্য টাকা মাত্র'],
    [7, 'সাত টাকা মাত্র'],
    [21, 'একুশ টাকা মাত্র'],
    [99, 'নিরানব্বই টাকা মাত্র'],
    [100, 'এক শত টাকা মাত্র'],
    [105, 'এক শত পাঁচ টাকা মাত্র'],
    [1000, 'এক হাজার টাকা মাত্র'],
    [12345, 'বারো হাজার তিন শত পঁয়তাল্লিশ টাকা মাত্র'],
    [100000, 'এক লক্ষ টাকা মাত্র'],
    [1395000, 'তেরো লক্ষ পঁচানব্বই হাজার টাকা মাত্র'],
    [10000000, 'এক কোটি টাকা মাত্র'],
    [999999999, 'নিরানব্বই কোটি নিরানব্বই লক্ষ নিরানব্বই হাজার নয় শত নিরানব্বই টাকা মাত্র'],
    [11, 'এগারো টাকা মাত্র'],
    [38, 'আটত্রিশ টাকা মাত্র'],
    [45, 'পঁয়তাল্লিশ টাকা মাত্র'],
    [76, 'ছিয়াত্তর টাকা মাত্র'],
    [88, 'আটাশি টাকা মাত্র'],
  ])('%i', (n, expected) => expect(w(n)).toBe(expected))

  it('rejects fractions, negatives and out-of-range amounts', () => {
    expect(() => w(1.5)).toThrow()
    expect(() => w(-1)).toThrow()
    expect(() => w(1e9)).toThrow()
  })
})
