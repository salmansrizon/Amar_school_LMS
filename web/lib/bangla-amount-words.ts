function words(n: number): string {
  const parts: string[] = []
  const unit = (v: number, name: string) => {
    if (v) parts.push(`${U[v]} ${name}`)
  }
  unit(Math.floor(n / 1e7), 'কোটি')
  unit(Math.floor((n % 1e7) / 1e5), 'লক্ষ')
  unit(Math.floor((n % 1e5) / 1e3), 'হাজার')
  unit(Math.floor((n % 1e3) / 100), 'শত')
  if (n % 100) parts.push(U[n % 100])
  return parts.join(' ')
}

export function banglaAmountInWords(n: number): string {
  if (!Number.isInteger(n) || n < 0 || n > 999999999) throw new Error('amount must be a whole number from 0 to 99,99,99,999')
  return `${n === 0 ? U[0] : words(n)} টাকা মাত্র`
}
